const stored = await page.evaluate(() => localStorage.getItem('veilpass.vault.v1'));
if (!stored || stored.includes('studentId') || stored.includes('graduationYear')) throw new Error('Vault encryption failed');
await page.screenshot({ path: 'docs/screenshots/credential.png', fullPage: true });
await page.getByRole('button', {name:'Lock vault',exact:true}).click();
await page.getByLabel('Vault passphrase').fill('wrong-passphrase');
await page.getByRole('button',{name:'Unlock private vault'}).click();
