await page.goto('http://127.0.0.1:3000');
await page.getByRole('heading', { name: /Prove what matters/ }).waitFor();
await mkdir('docs/screenshots', {recursive:true});
await page.screenshot({ path: 'docs/screenshots/overview.png', fullPage: true });
await page.getByRole('button', { name: 'Launch demo', exact: true }).click();
await page.getByLabel('Vault passphrase').fill('veilpass-test-passphrase');
await page.getByRole('button', { name: 'Get Demo Credential', exact: true }).click();
