await page.getByLabel('Vault passphrase').fill('veilpass-test-passphrase');
await page.getByRole('button',{name:'Unlock private vault'}).click();
await page.getByRole('button',{name:'Prove my eligibility'}).click();
await page.getByRole('button',{name:'Connect wallet to continue'}).click();
await page.getByRole('heading',{name:'No Midnight wallet detected'}).waitFor();
await page.getByRole('button',{name:'Close wallet selection'}).click();
await page.screenshot({path:'docs/screenshots/verification.png',fullPage:true});
